using System.Text;

namespace MapLean.Generator;

internal static class SourceEmitter
{
    public static string Emit(MapContract contract)
    {
        var preludes = new List<string>();
        var expression = EmitExpr(contract.Root, preludes);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        var indent = "";
        if (contract.Namespace is not null)
        {
            builder.Append("namespace ").AppendLine(contract.Namespace);
            builder.AppendLine("{");
            indent = "    ";
        }

        builder.Append(indent).Append(contract.TypeAccessibility).Append(' ');
        if (contract.TypeIsStatic)
            builder.Append("static ");
        builder.Append("partial class ").AppendLine(contract.TypeName);
        builder.Append(indent).AppendLine("{");
        builder.Append(indent).Append("    ").Append(contract.MethodAccessibility).Append(' ');
        if (contract.MethodIsStatic)
            builder.Append("static ");
        builder.Append("partial ").Append(contract.DestType).Append(' ').Append(contract.MethodName).Append('(');
        builder.Append(contract.SourceType).Append(' ').Append(contract.ParameterName).AppendLine(")");
        builder.Append(indent).AppendLine("    {");
        foreach (var line in preludes)
            builder.Append(indent).Append("        ").AppendLine(line);
        builder.Append(indent).Append("        return ").Append(expression).AppendLine(";");
        builder.Append(indent).AppendLine("    }");
        builder.Append(indent).AppendLine("}");
        if (contract.Namespace is not null)
            builder.AppendLine("}");
        return builder.ToString();
    }

    private static string EmitExpr(Plan plan, List<string> preludes)
    {
        switch (plan)
        {
            case Plan.Copy copy:
                return copy.Path;
            case Plan.Nested nested:
            {
                var ctorArgs = new List<string>();
                var initArgs = new List<string>();
                var deferred = new List<string>();
                for (var i = 0; i < nested.Args.Length; i++)
                {
                    var local = new List<string>();
                    var expr = EmitExpr(nested.Args[i].Value, local);
                    if (local.Exists(static line => line.StartsWith("for ", StringComparison.Ordinal)))
                        preludes.AddRange(local);
                    else
                        deferred.AddRange(local);
                    if (i < nested.CtorCount)
                        ctorArgs.Add(expr);
                    else
                        initArgs.Add(nested.Args[i].Name + " = " + expr);
                }

                preludes.AddRange(deferred);

                var created = "new " + nested.Type + "(" + string.Join(", ", ctorArgs) + ")";
                if (initArgs.Count == 0)
                    return created;
                return created + " { " + string.Join(", ", initArgs) + " }";
            }
            case Plan.NullNested nullNested:
            {
                preludes.Add($"var {nullNested.Local} = {nullNested.Path};");
                var inner = new List<string>();
                var args = new string[nullNested.Args.Length];
                for (var i = 0; i < nullNested.Args.Length; i++)
                    args[i] = EmitExpr(nullNested.Args[i].Value, inner);
                preludes.AddRange(inner);
                return $"{nullNested.Local} is null ? null : new {nullNested.Type}(" + string.Join(", ", args) + ")";
            }
            case Plan.List list:
            {
                var elementPreludes = new List<string>();
                var element = EmitExpr(list.Element, elementPreludes);
                var src = list.Local;
                preludes.Add($"var {src} = {list.Path};");
                preludes.Add($"var {src}Count = {src}.Count;");
                preludes.Add($"var {src}Mapped = new global::System.Collections.Generic.List<{list.ElementType}>({src}Count);");
                preludes.Add($"for (var {src}I = 0; {src}I < {src}Count; {src}I++)");
                preludes.Add("{");
                preludes.Add($"    var {src}Item = {src}[{src}I];");
                foreach (var line in elementPreludes)
                    preludes.Add("    " + line);
                preludes.Add($"    {src}Mapped.Add({element});");
                preludes.Add("}");
                return src + "Mapped";
            }
            default:
                return "default";
        }
    }
}
